#!/usr/bin/env node
// Writes the Homebrew cask and the AUR package (PKGBUILD) for one release, from
// packaging/package-managers.json and the release's SHA256SUMS: nothing is rebuilt, both point at
// files already on the GitHub release. Used by .github/workflows/package-managers.yml.
//
//   node scripts/package-managers-unix.mjs --version 1.1.0 --sums path/to/SHA256SUMS --out out/package-managers
//
// The AUR .SRCINFO needs makepkg, so the workflow writes it in an Arch container.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';

const { values: args } = parseArgs({
  options: {
    version: { type: 'string' },
    sums: { type: 'string' },
    repo: { type: 'string', default: process.env.GITHUB_REPOSITORY || 'davidemaggi/Hodor' },
    out: { type: 'string', default: 'out/package-managers' },
  },
});
if (!args.version || !args.sums) fail('--version and --sums are required');

const root = new URL('..', import.meta.url);
const meta = JSON.parse(readFileSync(new URL('packaging/package-managers.json', root), 'utf-8'));
const version = args.version.replace(/^v/, '');
/** Release download URL; `ver` is the version as the target format writes it (a variable there) */
const download = (file, ver = version) =>
  `https://github.com/${args.repo}/releases/download/v${ver}/${file}`;

// SHA256SUMS lines: "<hash>  <file>"
const sums = new Map(
  readFileSync(args.sums, 'utf-8')
    .split('\n')
    .map((line) => line.trim().split(/\s+\*?/))
    .filter(([hash, file]) => hash && file)
    .map(([hash, file]) => [file, hash.toLowerCase()])
);
const sumOf = (file) => sums.get(file) ?? fail(`${file} isn't in SHA256SUMS`);
const assetFor = (template, arch) => template.replace('{version}', version).replace('{arch}', arch);
const en = meta.locales['en-US'];

// ── Homebrew cask ───────────────────────────────────────────────────────────────────────────────
const brew = meta.homebrew;
const brewDir = join(args.out, 'homebrew', 'Casks');
mkdirSync(brewDir, { recursive: true });
const brewArch = Object.entries(brew.arches); // [['arm', 'arm64'], ['intel', 'x64']]
const sha = brewArch.map(([key, arch]) => `${key}: "${sumOf(assetFor(brew.asset, arch))}"`);
const urlPattern = download(
  brew.asset.replace('{version}', '#{version}').replace('{arch}', '#{arch}'),
  '#{version}'
);
const appdirPath = (inside) => `"#{appdir}/${brew.app}/${inside}"`;

writeFileSync(
  join(brewDir, `${brew.cask}.rb`),
  `cask "${brew.cask}" do
  arch ${brewArch.map(([key, arch]) => `${key}: "${arch}"`).join(', ')}

  version "${version}"
  sha256 ${sha.join(',\n         ')}

  url "${urlPattern}"
  name "${meta.name}"
  desc "${en.shortDescription.replace(/\.$/, '').replace(/"/g, '\\"')}"
  homepage "${meta.projectUrl}"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: ">= :${brew.minimumMacOS}"

  app "${brew.app}"
${brew.binaries.map((b) => `  binary ${appdirPath(b)}`).join('\n')}
${
  brew.removeQuarantine
    ? `
  # Not notarized by Apple yet: without this, macOS refuses to open it the first time
  postflight do
    system_command "/usr/bin/xattr",
                   args: ["-dr", "com.apple.quarantine", "#{appdir}/${brew.app}"]
  end
`
    : ''
}
  zap trash: [
${brew.zap.map((p) => `    "${p}",`).join('\n')}
  ]
end
`
);

// ── AUR ─────────────────────────────────────────────────────────────────────────────────────────
const aur = meta.aur;
const aurDir = join(args.out, 'aur', aur.package);
mkdirSync(aurDir, { recursive: true });
const aurArch = Object.entries(aur.arches); // [['x86_64', 'amd64'], ['aarch64', 'arm64']]
const quote = (s) => `'${s.replace(/'/g, `'"'"'`)}'`;
const sourceName = (arch) => `${aur.provides}-\${pkgver}-${arch}.deb`;

writeFileSync(
  join(aurDir, 'PKGBUILD'),
  `# Maintainer: ${aur.maintainer}
# Generated by ${meta.projectUrl}/blob/main/scripts/package-managers-unix.mjs from the release's
# own .deb: the app isn't rebuilt here.

pkgname=${aur.package}
pkgver=${version}
pkgrel=1
pkgdesc=${quote(en.shortDescription)}
arch=(${aurArch.map(([a]) => quote(a)).join(' ')})
url=${quote(meta.projectUrl)}
license=(${quote(meta.license)})
depends=(${aur.depends.map(quote).join(' ')})
optdepends=(${aur.optdepends.map(quote).join(' ')})
provides=(${quote(aur.provides)})
conflicts=(${quote(aur.provides)})
options=('!strip' '!debug')
${aurArch
  .map(
    ([arch, debArch]) =>
      `source_${arch}=("${sourceName(arch)}::${download(aur.asset.replace('{version}', '${pkgver}').replace('{arch}', debArch), '${pkgver}')}")`
  )
  .join('\n')}
${aurArch
  .map(([arch, debArch]) => `sha256sums_${arch}=('${sumOf(assetFor(aur.asset, debArch))}')`)
  .join('\n')}

package() {
  bsdtar -xf data.tar.xz -C "$pkgdir"
  rm -rf "$pkgdir/usr/share/doc"
  # Chromium's sandbox helper must be setuid root when user namespaces are off
  chmod 4755 "$pkgdir${aur.installDir}/chrome-sandbox"
  install -d "$pkgdir/usr/bin"
${Object.entries(aur.links)
  .map(([link, target]) => `  ln -s ${quote(target)} "$pkgdir${link}"`)
  .join('\n')}
}
`
);

console.log(JSON.stringify({ version, homebrew: brewDir, aur: aurDir }, null, 2));

function fail(message) {
  console.error(`package-managers-unix: ${message}`);
  process.exit(1);
}
